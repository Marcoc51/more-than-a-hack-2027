import s1Json from '../scenario/generated/s1.json';
import { labelAt, runs } from '../scenario/labels';
import { SCENARIOS } from '../scenario/scenarios';
import { ScenarioError, parseScenario } from '../scenario/validate';

const s1 = SCENARIOS[0]!;
const clone = () => JSON.parse(JSON.stringify(s1Json)) as Record<string, any>;

describe('scenario S1 (generated by tools/export_scenarios.py)', () => {
  it('has consistent frame numbering and counts', () => {
    expect(s1.frameCount).toBe(400);
    expect(s1.frames).toHaveLength(s1.frameCount);
    expect(s1.fps).toBe(25);
    expect(s1.graded).toEqual([[25, 375]]);
  });

  it('references only declared teams and keeps one position slot per player', () => {
    const ids = new Set(s1.teams.map((t) => t.id));
    expect(s1.teams.map((t) => t.side).sort()).toEqual(['away', 'home']);
    for (const p of s1.players) expect(ids.has(p.teamId)).toBe(true);
    for (const f of s1.frames) expect(f.players).toHaveLength(s1.players.length);
  });

  it('keeps player positions on or near the pitch', () => {
    for (const f of s1.frames) {
      for (const p of f.players) {
        if (!p) continue;
        expect(p[0]).toBeGreaterThan(-5);
        expect(p[0]).toBeLessThan(s1.pitch.length + 5);
        expect(p[1]).toBeGreaterThan(-5);
        expect(p[1]).toBeLessThan(s1.pitch.width + 5);
      }
    }
  });

  it('has missing observations where the script removes them', () => {
    const missingBall = s1.frames.filter((f) => f.ball === null).length;
    expect(missingBall).toBeGreaterThan(0);
    expect(s1.frames.some((f) => f.players.some((p) => p === null))).toBe(true);
  });

  it('aligns every model output with the frames', () => {
    const { phase3b, smooth50 } = s1.models;
    for (const s of [phase3b.labels, smooth50.labels, phase3b.evidence, smooth50.nearestTeam]) {
      expect(s).toHaveLength(s1.frameCount);
    }
    expect(phase3b.reasons).toHaveLength(s1.frameCount);
    s1.frames.forEach((f, i) => expect(f.ball === null).toBe(phase3b.evidence[i] === '_'));
  });

  it('labels the ungraded frames X in the Phase 3B output', () => {
    for (let f = 0; f < 25; f++) expect(labelAt(s1.models.phase3b.labels, f)).toBe('X');
    for (let f = 375; f < 400; f++) expect(labelAt(s1.models.phase3b.labels, f)).toBe('X');
  });

  it('records synthetic provenance', () => {
    expect(s1.provenance.kind).toBe('synthetic');
    expect(s1.provenance.generator).toBe('tools/export_scenarios.py');
    expect(s1.provenance.engineCommit).toMatch(/^[0-9a-f]{40}$/);
    expect(Object.keys(s1.provenance.engineFiles)).toContain('src/possession.py');
  });

  it('keeps reference labels separate from model predictions', () => {
    expect(s1.reference?.source).toBe('scenario-script');
    expect(Object.keys(s1.models).sort()).toEqual(['phase3b', 'smooth50']);
  });
});

describe('parseScenario rejects bad input', () => {
  it('refuses non-synthetic data', () => {
    const bad = clone();
    bad.provenance.kind = 'match';
    expect(() => parseScenario(bad)).toThrow(ScenarioError);
  });
  it('refuses misaligned labels', () => {
    const bad = clone();
    bad.models.smooth50.labels = 'H'.repeat(399);
    expect(() => parseScenario(bad)).toThrow(/expected 400 labels/);
  });
  it('refuses unknown labels and unknown teams', () => {
    const a = clone();
    a.models.phase3b.labels = 'Q' + a.models.phase3b.labels.slice(1);
    expect(() => parseScenario(a)).toThrow(/unexpected label/);
    const b = clone();
    b.players[0].teamId = 'nobody';
    expect(() => parseScenario(b)).toThrow(/unknown team/);
  });
  it('refuses a ball that disagrees with the engine evidence', () => {
    const bad = clone();
    const i = bad.frames.findIndex((f: { ball: unknown }) => f.ball === null);
    bad.frames[i].ball = [1, 1, 0];
    expect(() => parseScenario(bad)).toThrow(/disagree/);
  });
});

describe('runs', () => {
  it('produces exact half-open boundaries', () => {
    expect(runs('XXHHHD')).toEqual([
      { value: 'X', start: 0, end: 2 },
      { value: 'H', start: 2, end: 5 },
      { value: 'D', start: 5, end: 6 },
    ]);
    expect(runs('')).toEqual([]);
  });
  it('covers every frame of the S1 timeline exactly once', () => {
    const r = runs(s1.models.phase3b.labels);
    expect(r[0]!.start).toBe(0);
    expect(r[r.length - 1]!.end).toBe(s1.frameCount);
    r.slice(1).forEach((run, i) => expect(run.start).toBe(r[i]!.end));
  });
});
